import assert from "node:assert/strict";
import path from "node:path";
import { pathToFileURL } from "node:url";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(path.join(process.env.PLAYWRIGHT_MODULE, "index.mjs")).href : "playwright");
const origin = process.argv[2] || "http://localhost:3000";
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
try {
  const context = await browser.newContext();
  await context.addInitScript(() => {
    window.reducedRouteAnimations = [];
    const animate = Element.prototype.animate;
    Element.prototype.animate = function(frames, options) {
      if (options?.pseudoElement?.startsWith("::view-transition-") && matchMedia("(prefers-reduced-motion: reduce)").matches) window.reducedRouteAnimations.push(options.duration);
      return animate.call(this, frames, options);
    };
  });
  const page = await context.newPage();
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const settle = () => page.waitForFunction(() => !document.getAnimations().some(animation => animation.effect?.pseudoElement?.startsWith("::view-transition-")));
  const checkTransition = async () => {
    await page.waitForFunction(() => document.getAnimations().some(animation => animation.effect?.pseudoElement?.startsWith("::view-transition-new(")));
    const motion = await page.evaluate(() => {
      const animations = document.getAnimations();
      const incoming = animations.find(animation => animation.animationName === "route-arrive" && animation.effect?.pseudoElement?.startsWith("::view-transition-new("));
      const outgoing = animations.find(animation => !animation.animationName && animation.effect?.pseudoElement?.startsWith("::view-transition-old("));
      const group = animations.find(animation => animation.effect?.pseudoElement?.startsWith("::view-transition-group(") && animation.effect.pseudoElement !== "::view-transition-group(root)");
      const frames = group.effect.getKeyframes();
      const oldFrame = outgoing.effect.getKeyframes()[0];
      const before = new DOMMatrix(frames[0].transform), after = new DOMMatrix(frames.at(-1).transform), offset = new DOMMatrix(oldFrame.transform);
      const arrival = incoming.effect.getKeyframes();
      return { duration: incoming.effect.getTiming().duration, delay: incoming.effect.getTiming().delay, arrivalY: new DOMMatrix(arrival[0].transform).f, endTransform: arrival.at(-1).transform, exit: outgoing.effect.getTiming().duration, width: oldFrame.width, oldWidth: frames[0].width, dx: after.e + offset.e - before.e, dy: after.f + offset.f - before.f, groupFinished: group.playState, titleAnimations: document.querySelector("h1").getAnimations().length };
    });
    assert.equal(motion.duration, 300);
    assert.equal(motion.delay, 180, "new content follows the old content's departure");
    assert.equal(motion.arrivalY, 6, "page content receives one bounded spatial arrival");
    assert.equal(motion.endTransform, "none", "arrival releases the snapshot to its natural position");
    assert.equal(motion.exit, 180);
    assert.equal(motion.width, motion.oldWidth, "old snapshot keeps its original text/image width");
    assert.ok(Math.abs(motion.dx) < 1 && Math.abs(motion.dy) < 1, "old snapshot stays at its original viewport position");
    assert.equal(motion.groupFinished, "finished", "page height and scroll offset do not morph");
    assert.equal(motion.titleAnimations, 0, "page transition does not replay the title entrance");
    await settle();
  };
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: width < 760 ? 844 : 1000 });
    await page.goto(origin);
    await page.getByRole("link", { name: "作品", exact: true }).click();
    await page.waitForURL(origin + "/projects");
    await checkTransition();
    await page.locator('[data-project="pyscreen"]').click();
    await page.waitForURL(origin + "/projects/pyscreen");
    await checkTransition();
    await page.getByRole("button", { name: "看反馈", exact: false }).click();
    assert.equal(await page.locator("#process-explanation .state-arrival").evaluate(element => getComputedStyle(element).animationName), "appear", "explanation arrives with its spotlight");
    await page.getByRole("link", { name: "手记", exact: true }).click();
    await page.waitForURL(origin + "/blog");
    await checkTransition();
    await page.locator(".note-feature").click();
    await page.waitForURL(origin + "/blog/motion-for-understanding");
    await checkTransition();
    const adjacent = page.getByRole("navigation", { name: "继续阅读" }).getByRole("link").last();
    await adjacent.scrollIntoViewIfNeeded();
    const previousScroll = await page.evaluate(() => scrollY);
    const href = await adjacent.getAttribute("href");
    await adjacent.click();
    await page.waitForURL(origin + href);
    await checkTransition();
    assert.equal(await page.evaluate(() => scrollY), 0, "next article opens at the top without smooth-scroll drift");
    await page.goBack();
    await page.waitForURL(origin + "/blog/motion-for-understanding");
    await settle();
    const restoredScroll = await page.evaluate(() => scrollY);
    assert.ok(Math.abs(restoredScroll - previousScroll) < 3, `browser back restores reading position: ${restoredScroll} vs ${previousScroll}`);
    await page.goForward();
    await page.waitForURL(origin + href);
    await settle();
    assert.equal(await page.locator("#main-content").count(), 1);
    await page.goto(origin);
    // Navigation stays unnamed and available while the content snapshot is animating.
    for (const name of ["作品", "关于", "手记"]) await page.getByRole("link", { name, exact: true }).click();
    await page.waitForURL(origin + "/blog");
    await settle();
    assert.equal(await page.locator("h1").count(), 1, "rapid navigation keeps the last destination");
    await page.getByRole("link", { name: "关于", exact: true }).click();
    await page.waitForURL(origin + "/about");
    await page.waitForFunction(() => document.getAnimations().some(animation => animation.effect?.pseudoElement?.startsWith("::view-transition-new(")));
    await page.emulateMedia({ reducedMotion: "reduce" });
    await settle();
    assert.equal(await page.locator("h1").evaluate(element => getComputedStyle(element).opacity), "1");
    await page.getByRole("link", { name: "作品", exact: true }).click();
    await page.waitForURL(origin + "/projects");
    await settle();
    assert.deepEqual(await page.evaluate(() => window.reducedRouteAnimations), [], "already reduced motion never starts an explicit route animation");
    await page.emulateMedia({ reducedMotion: "no-preference" });
  }
  const slow = await context.newPage();
  slow.on("pageerror", error => errors.push(error.message));
  await slow.route("**/about?*", async route => { await new Promise(resolve => setTimeout(resolve, 700)); await route.continue(); });
  await slow.goto(origin);
  await slow.getByRole("link", { name: "关于", exact: true }).dispatchEvent("click");
  await slow.waitForTimeout(120);
  assert.ok((await slow.locator("h1").textContent()).includes("Vibe Coding"), "slow route keeps the existing page while content is fetched");
  await slow.waitForURL(origin + "/about");
  await slow.waitForFunction(() => !document.getAnimations().some(animation => animation.effect?.pseudoElement));
  await slow.close();
  const fallback = await context.newPage();
  fallback.on("pageerror", error => errors.push(error.message));
  await fallback.addInitScript(() => { document.startViewTransition = undefined; });
  await fallback.goto(origin);
  await fallback.getByRole("link", { name: "作品", exact: true }).click();
  await fallback.waitForURL(origin + "/projects");
  await fallback.waitForFunction(() => document.querySelector("h1").getAnimations().some(animation => animation.playState === "running"));
  await fallback.waitForFunction(() => document.querySelector("h1").getAnimations().length === 0);
  assert.equal(await fallback.locator("h1").evaluate(element => getComputedStyle(element).clipPath), "none", "unsupported browser remains fully readable");
  assert.deepEqual(errors, []);
  console.log("PASS: desktop/mobile route snapshots, original geometry, sequencing, article top/back/forward, rapid navigation, reduced motion, delayed content and unsupported-browser fallback.");
} finally { await browser.close(); }
